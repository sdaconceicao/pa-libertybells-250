export function getCountyCentroid(
	county: string,
): { lat: number; lng: number } | null {
	const key = county
		.trim()
		.toUpperCase()
		.replace(/\s+COUNTY$/i, "");
	return PA_COUNTY_CENTROIDS[key] ?? null;
}
